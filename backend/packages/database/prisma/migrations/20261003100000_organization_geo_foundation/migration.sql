-- Additive read-model only; frozen economic facts are untouched.
CREATE TABLE organization.geo_admin_area (
 area_code text PRIMARY KEY,
 country_code text NOT NULL,
 level text NOT NULL CHECK (level IN ('CITY','DISTRICT')),
 parent_area_code text REFERENCES organization.geo_admin_area(area_code),
 area_name_zh text NOT NULL,
 area_name_en text,
 region_group text NOT NULL CHECK(region_group IN ('NORTH','CENTRAL','SOUTH','EAST','ISLAND')),
 sort_order integer NOT NULL,
 is_active boolean NOT NULL DEFAULT true,
 definition_version text NOT NULL,
 CHECK ((level='CITY' AND parent_area_code IS NULL) OR (level='DISTRICT' AND parent_area_code IS NOT NULL))
);
CREATE INDEX geo_admin_area_parent_idx ON organization.geo_admin_area(parent_area_code,sort_order);

CREATE TABLE identity.member_geo_profile (
 member_id uuid PRIMARY KEY REFERENCES identity.person(person_id),
 country_code text NOT NULL,
 city_code text REFERENCES organization.geo_admin_area(area_code),
 district_code text REFERENCES organization.geo_admin_area(area_code),
 geo_status text NOT NULL CHECK(geo_status IN ('PENDING','NORMALIZED','PARTIAL','FAILED','MANUAL_CONFIRMED')),
 geo_source text NOT NULL,
 geo_confidence numeric(5,4) NOT NULL CHECK(geo_confidence BETWEEN 0 AND 1),
 reason_code text,
 address_hash text NOT NULL CHECK(address_hash ~ '^[a-f0-9]{64}$'),
 source_snapshot_id uuid NOT NULL REFERENCES identity.formal_member_application_snapshot(formal_member_application_snapshot_id),
 source_effective_at timestamptz NOT NULL,
 source_recorded_at timestamptz NOT NULL,
 normalized_at timestamptz NOT NULL,
 definition_version text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK(district_code IS NULL OR city_code IS NOT NULL)
);
CREATE INDEX member_geo_profile_area_idx ON identity.member_geo_profile(city_code,district_code,member_id);

-- Immutable historical classification; do not read today's location for a past checkpoint.
CREATE TABLE identity.member_geo_profile_version (
 geo_profile_version_id uuid PRIMARY KEY,
 member_id uuid NOT NULL REFERENCES identity.person(person_id),
 country_code text NOT NULL,
 city_code text REFERENCES organization.geo_admin_area(area_code),
 district_code text REFERENCES organization.geo_admin_area(area_code),
 geo_status text NOT NULL CHECK(geo_status IN ('PENDING','NORMALIZED','PARTIAL','FAILED','MANUAL_CONFIRMED')),
 geo_source text NOT NULL,
 geo_confidence numeric(5,4) NOT NULL CHECK(geo_confidence BETWEEN 0 AND 1),
 reason_code text,
 address_hash text NOT NULL CHECK(address_hash ~ '^[a-f0-9]{64}$'),
 source_snapshot_id uuid NOT NULL REFERENCES identity.formal_member_application_snapshot(formal_member_application_snapshot_id),
 source_effective_at timestamptz NOT NULL,
 source_recorded_at timestamptz NOT NULL,
 normalized_at timestamptz NOT NULL,
 definition_version text NOT NULL,
 UNIQUE(member_id,source_snapshot_id,definition_version),
 CHECK(district_code IS NULL OR city_code IS NOT NULL)
);
CREATE INDEX member_geo_profile_version_time_idx ON identity.member_geo_profile_version(member_id,source_effective_at,source_recorded_at);
