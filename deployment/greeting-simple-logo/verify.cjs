const fs=require('fs'),p=require('path'),assert=require('assert'),root=p.resolve(__dirname,'../..');
const ts=require(require.resolve('typescript',{paths:[p.join(root,'backend')]}));
const src=p.join(root,'backend/apps/api/src/modules/daily-greetings'),out=p.join(root,'deployment/greeting-simple-logo/candidate');
fs.mkdirSync(out,{recursive:true});fs.mkdirSync(p.join(out,'assets'),{recursive:true});
for(const name of ['greeting-brand','greeting-upload','render-greeting'])fs.writeFileSync(p.join(out,name+'.js'),ts.transpileModule(fs.readFileSync(p.join(src,name+'.ts'),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText);
for(const name of ['ucell-simple-logo.png','ucell-line-qr.png'])fs.copyFileSync(p.join(src,'assets',name),p.join(out,'assets',name));
const png=require(p.join(root,'deployment/greeting-simple-logo/tools/node_modules/pngjs')).PNG;
const jsqr=require(p.join(root,'deployment/greeting-simple-logo/tools/node_modules/jsqr'));
const decode=b=>{const x=png.sync.read(b);return jsqr(new Uint8ClampedArray(x.data),x.width,x.height)?.data;};
assert.equal(decode(fs.readFileSync(p.join(out,'assets/ucell-line-qr.png'))),'https://lin.ee/pqS11xX');
const upload=require(p.join(out,'greeting-upload'));
(async()=>{const fixture=fs.readFileSync(p.join(root,'member/tests/fixtures/daily-greeting-2026-11-11.png'));
assert.equal(upload.imageType(fixture),'png');
assert.throws(()=>upload.imageType(Buffer.alloc(3145729)));
assert.throws(()=>upload.imageType(Buffer.from('<svg/>')));
await assert.rejects(upload.normalizeGreetingUpload('not base64'));
const result=await upload.normalizeGreetingUpload(fixture.toString('base64'));
assert.equal(result.readUInt32BE(16),1080);assert.equal(result.readUInt32BE(20),1080);
assert.equal(decode(result),'https://lin.ee/pqS11xX');
fs.mkdirSync(p.join(root,'deployment/greeting-simple-logo/preview'),{recursive:true});
fs.writeFileSync(p.join(root,'deployment/greeting-simple-logo/preview/upload.png'),result);
console.log(JSON.stringify({checks:7,resultBytes:result.length,qr:'https://lin.ee/pqS11xX',pass:true}));})().catch(e=>{console.error(e);process.exitCode=1});
